-- Travel Destination Planner
-- Schema derived from the current JPA entities.
-- Destination and app_users are currently independent entities.

CREATE TABLE destination (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(100) NOT NULL,
    capital VARCHAR(100) NOT NULL,
    region VARCHAR(100) NOT NULL,
    population BIGINT NOT NULL,
    currency VARCHAR(100) NOT NULL,
    flag_url VARCHAR(500) NOT NULL,

    CONSTRAINT chk_destination_population_positive
        CHECK (population > 0)
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(128) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(45) NOT NULL,
    last_name VARCHAR(45) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',

    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT chk_app_users_role
        CHECK (role IN ('USER', 'ADMIN'))
);
